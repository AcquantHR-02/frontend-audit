/**
 * Mock file storage. The real backend keeps uploads in object storage and returns download
 * URLs; here the bytes live in IndexedDB (in memory under tests) and are served by the
 * GET /files/:id handler, so previews and downloads survive a page reload.
 * Seeded demo files have no stored bytes: the handler renders a sample document instead.
 */
import type { StoredFile } from "@/types/domain";
import { apiUrl, newId } from "./utils";

const DB_NAME = "ams.mock-files";
const STORE = "files";
const memory = new Map<string, Blob>();

function openDb(): Promise<IDBDatabase> | null {
  if (typeof indexedDB === "undefined") return null;
  return new Promise((resolve, reject) => {
    const request = indexedDB.open(DB_NAME, 1);
    request.onupgradeneeded = () => request.result.createObjectStore(STORE);
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error);
  });
}

async function idb<T>(mode: IDBTransactionMode, run: (store: IDBObjectStore) => IDBRequest<T>): Promise<T | null> {
  const opening = openDb();
  if (!opening) return null;
  try {
    const db = await opening;
    return await new Promise<T>((resolve, reject) => {
      const request = run(db.transaction(STORE, mode).objectStore(STORE));
      request.onsuccess = () => resolve(request.result);
      request.onerror = () => reject(request.error);
    });
  } catch {
    return null; // Storage blocked or full: the file stays in memory for this session.
  }
}

export const fileUrl = (id: string) => apiUrl(`/files/${id}`);

/** Saves an uploaded file and returns the metadata stored on the record. */
export async function storeUpload(file: File): Promise<StoredFile> {
  const id = newId("file");
  memory.set(id, file);
  await idb("readwrite", (store) => store.put(file, id));
  return {
    id,
    fileName: file.name,
    contentType: file.type || "application/octet-stream",
    sizeBytes: file.size,
    url: fileUrl(id),
  };
}

export async function loadFile(id: string): Promise<Blob | null> {
  const cached = memory.get(id);
  if (cached) return cached;
  const stored = await idb<Blob | undefined>("readonly", (store) => store.get(id));
  if (stored) memory.set(id, stored);
  return stored ?? null;
}

/** Drops every stored upload (used by "Reset demo data"). */
export async function clearFiles() {
  memory.clear();
  await idb("readwrite", (store) => store.clear());
}

/* ---------- Sample documents for seeded evidence ---------- */

/** One-page PDF with the given lines (Helvetica, A4). Valid xref so every viewer opens it. */
export function samplePdf(title: string, lines: string[]): Blob {
  const esc = (text: string) => text.replace(/[\\()]/g, (c) => `\\${c}`).replace(/[^\x20-\x7e]/g, "-");
  const body = [
    "BT /F2 18 Tf 56 770 Td (" + esc(title) + ") Tj ET",
    "0.85 0.89 0.95 rg 56 748 483 2 re f 0 0 0 rg",
    ...lines.map((line, i) => `BT /F1 11 Tf 56 ${720 - i * 20} Td (${esc(line)}) Tj ET`),
    "0.6 0.6 0.6 rg BT /F1 9 Tf 56 60 Td (Sample document generated by the demo backend.) Tj ET",
  ].join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>",
    `<< /Length ${body.length} >>\nstream\n${body}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
    `<< /Title (${esc(title)}) /Producer (Audit Management demo) >>`,
  ];
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((object, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("");
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R /Info ${objects.length} 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return new Blob([pdf], { type: "application/pdf" });
}

/** A "photo" of a register page as SVG, for image evidence. */
export function sampleImage(title: string, lines: string[]): Blob {
  const esc = (text: string) => text.replace(/[<>&"]/g, (c) => `&#${c.charCodeAt(0)};`);
  const rows = lines
    .map((line, i) => `<text x="48" y="${170 + i * 34}" font-size="20" fill="#334155">${esc(line)}</text>`)
    .join("");
  const ruled = Array.from(
    { length: 14 },
    (_, i) => `<line x1="40" x2="760" y1="${180 + i * 34}" y2="${180 + i * 34}" stroke="#cbd5e1"/>`,
  ).join("");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="680" viewBox="0 0 800 680">
<rect width="800" height="680" fill="#f1f5f9"/><rect x="24" y="24" width="752" height="632" rx="10" fill="#fffdf6" stroke="#e2e8f0"/>
<text x="48" y="92" font-family="Georgia,serif" font-size="30" font-weight="bold" fill="#0f172a">${esc(title)}</text>
<line x1="40" x2="760" y1="116" y2="116" stroke="#1e3a8a" stroke-width="3"/>
<g font-family="Segoe UI,Arial,sans-serif">${ruled}${rows}</g>
<g transform="rotate(-12 600 560)"><rect x="500" y="520" width="210" height="80" rx="8" fill="none" stroke="#b91c1c" stroke-width="4" opacity=".7"/>
<text x="605" y="570" text-anchor="middle" font-family="Arial" font-size="26" font-weight="bold" fill="#b91c1c" opacity=".7">SITE COPY</text></g>
</svg>`;
  return new Blob([svg], { type: "image/svg+xml" });
}
